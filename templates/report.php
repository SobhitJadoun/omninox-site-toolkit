<?php
/**
 * Printable audit report.
 *
 * @package OmninoxSiteToolkit
 * @var array $results  Module results.
 * @var array $branding Branding.
 * @var int   $overall  Overall score.
 */

defined( 'ABSPATH' ) || exit;

$omninox_severity_labels = array(
	'critical' => __( 'Critical', 'omninox-site-toolkit'),
	'warning'  => __( 'Warning', 'omninox-site-toolkit'),
	'notice'   => __( 'Notice', 'omninox-site-toolkit'),
	'pass'     => __( 'Pass', 'omninox-site-toolkit'),
);
?>
<!DOCTYPE html>
<html lang="<?php echo esc_attr( get_bloginfo( 'language' ) ); ?>">
<head>
<meta charset="<?php echo esc_attr( get_bloginfo( 'charset' ) ); ?>">
<title><?php echo esc_html( sprintf( /* translators: %s: site name */ __( 'Website audit — %s', 'omninox-site-toolkit' ), get_bloginfo( 'name' ) ) ); ?></title>
<?php wp_print_styles( 'omninox-site-toolkit-report' ); ?>
</head>
<body>
<header>
	<div>
		<?php if ( $branding['logo_url'] ) : ?>
			<img src="<?php echo esc_url( $branding['logo_url'] ); ?>" alt="" style="max-height:48px;margin-bottom:10px">
		<?php endif; ?>
		<h1><?php echo esc_html( get_bloginfo( 'name' ) ); ?></h1>
		<div class="muted">
			<?php echo esc_html( home_url() ); ?> ·
			<?php echo esc_html( date_i18n( get_option( 'date_format' ) . ' ' . get_option( 'time_format' ) ) ); ?>
		</div>
	</div>
	<div class="score">
		<div class="value"><?php echo esc_html( $overall ); ?></div>
		<div class="muted"><?php esc_html_e( 'Overall score', 'omninox-site-toolkit'); ?></div>
	</div>
</header>

<div class="grid">
<?php foreach ( $results as $omninox_id => $omninox_result ) : ?>
	<div class="card">
		<span class="muted"><?php echo esc_html( $omninox_result['label'] ?? $omninox_id ); ?></span>
		<strong><?php echo esc_html( $omninox_result['score'] ?? 0 ); ?></strong>
		<span class="muted">
			<?php
			printf(
				/* translators: 1: critical count, 2: warning count */
				esc_html__( '%1$d critical · %2$d warnings', 'omninox-site-toolkit'),
				(int) ( $omninox_result['summary']['critical'] ?? 0 ),
				(int) ( $omninox_result['summary']['warning'] ?? 0 )
			);
			?>
		</span>
	</div>
<?php endforeach; ?>
</div>

<?php foreach ( $results as $omninox_id => $omninox_result ) : ?>
	<h2><?php echo esc_html( $omninox_result['label'] ?? $omninox_id ); ?></h2>
	<table>
		<thead>
			<tr>
				<th style="width:90px"><?php esc_html_e( 'Status', 'omninox-site-toolkit'); ?></th>
				<th><?php esc_html_e( 'Check', 'omninox-site-toolkit'); ?></th>
				<th style="width:22%"><?php esc_html_e( 'Result', 'omninox-site-toolkit'); ?></th>
				<th style="width:34%"><?php esc_html_e( 'What to do', 'omninox-site-toolkit'); ?></th>
			</tr>
		</thead>
		<tbody>
		<?php foreach ( (array) ( $omninox_result['issues'] ?? array() ) as $omninox_issue ) : ?>
			<?php $omninox_sev = $omninox_issue['severity'] ?? 'notice'; ?>
			<tr>
				<td><span class="sev sev-<?php echo esc_attr( $omninox_sev ); ?>"><?php echo esc_html( $omninox_severity_labels[ $omninox_sev ] ?? $omninox_sev ); ?></span></td>
				<td><?php echo esc_html( $omninox_issue['label'] ?? '' ); ?></td>
				<td><?php echo esc_html( is_scalar( $omninox_issue['value'] ?? '' ) ? $omninox_issue['value'] : '' ); ?></td>
				<td class="muted"><?php echo esc_html( $omninox_issue['description'] ?? '' ); ?></td>
			</tr>
		<?php endforeach; ?>
		</tbody>
	</table>
<?php endforeach; ?>

<footer>
	<?php if ( $branding['company'] ) : ?>
		<?php echo esc_html( $branding['company'] ); ?> ·
	<?php endif; ?>
	<?php if ( ! $branding['hide_credit'] ) : ?>
		<?php echo esc_html( sprintf( /* translators: %s: plugin name */ __( 'Generated by %s', 'omninox-site-toolkit'), $branding['plugin_name'] ) ); ?>
	<?php endif; ?>
</footer>
</body>
</html>
